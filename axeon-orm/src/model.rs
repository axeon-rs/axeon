//! The [`Model`] trait and the row operations behind the derived methods.

use crate::db::{Backend, Conn, Executor, Row};
use crate::error::{Error, Result};
use crate::query::Column;
use crate::sql::{column_list, Cond, Sql};
use crate::value::{Kind, Value};
use std::borrow::Cow;
use std::marker::PhantomData;

/// A Rust struct mapped to a database table.
///
/// Derive it with [`#[derive(Model)]`](derive@crate::Model), which also
/// adds these methods to the struct:
///
/// | Method | Does |
/// |---|---|
/// | `User::query()` | Starts a [`Query`](crate::Query) |
/// | `User::find(&db, id)` | Fetches by primary key: `Option<User>` |
/// | `User::find_or_fail(&db, id)` | Same, but [`Error::NotFound`] when missing |
/// | `User::all(&db)` | Every row |
/// | `user.insert(&db)` | Inserts, returning the stored row (with its new id) |
/// | `User::insert_many(&db, &users)` | Inserts many rows in a few statements, returning them in order |
/// | `User::upsert_many(&db, &users, OnConflict::on(User::EMAIL))` | The same, updating existing rows |
/// | `user.upsert(&db, OnConflict::on(User::EMAIL))` | Inserts, or updates the row with the same email; returns the stored row |
/// | `user.insert_or_ignore(&db, OnConflict::on(User::EMAIL))` | Inserts unless that row exists: `Option<User>` |
/// | `user.update(&db)` | Saves every column and reloads the row |
/// | `user.delete(&db)` | Deletes by primary key |
///
/// plus a typed [`Column`](crate::Column) constant per field (`User::EMAIL`)
/// and an accessor per relation (`user.posts()`).
pub trait Model: Sized + Send + Sync + Unpin + 'static {
    /// The table name.
    const TABLE: &'static str;
    /// The primary key column (the first one, for a composite key).
    const PRIMARY_KEY: &'static str;
    /// Every primary key column: one, or several for a composite key
    /// (several `#[model(primary_key)]` fields).
    const PRIMARY_KEYS: &'static [&'static str] = &[Self::PRIMARY_KEY];
    /// Every column, in field order.
    const COLUMNS: &'static [ColumnDef];
    /// The tenant column (`#[model(tenant)]`), if rows belong to tenants.
    /// Queries on such a model then need a tenant scope; see
    /// [`Db::for_tenant`](crate::Db::for_tenant).
    const TENANT: Option<&'static str> = None;
    /// The optimistic-locking version column (`#[model(version)]`), if
    /// any: updates and deletes of an instance only apply while the stored
    /// version still matches, and fail with
    /// [`Error::StaleRecord`](crate::Error::StaleRecord) otherwise.
    const VERSION: Option<&'static str> = None;
    /// Builds the model from a row holding all of its columns.
    fn from_row(row: &Row) -> Result<Self> {
        Self::from_row_prefixed(row, "")
    }
    /// Builds the model from a row whose column names start with `prefix`,
    /// as in a join.
    fn from_row_prefixed(row: &Row, prefix: &str) -> Result<Self>;
    /// The current value of a column, or `None` if there is no such column.
    fn get(&self, column: &str) -> Option<Value>;
}

/// Which timestamp the ORM keeps up to date in a column.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum Timestamp {
    /// Set to now on insert.
    CreatedAt,
    /// Set to now on insert and update.
    UpdatedAt,
}

/// A foreign key from a [`belongs_to`](derive@crate::Model) column.
#[derive(Clone, Copy, Debug)]
#[non_exhaustive]
pub struct Reference {
    /// The referenced table.
    pub table: &'static str,
    /// The referenced column.
    pub column: &'static str,
    /// The `ON DELETE` action, e.g. `CASCADE`.
    pub on_delete: Option<&'static str>,
}

/// A column's definition, generated by the derive.
#[derive(Clone, Copy, Debug)]
#[non_exhaustive]
pub struct ColumnDef {
    /// The column name.
    pub name: &'static str,
    /// Its SQL type.
    pub kind: Kind,
    /// Whether it allows `NULL`.
    pub nullable: bool,
    /// Whether it is the primary key.
    pub primary_key: bool,
    /// Whether the database assigns it on insert (integer primary keys).
    pub auto_increment: bool,
    /// Whether it has a unique constraint.
    pub unique: bool,
    /// Whether it has an index.
    pub index: bool,
    /// Whether the database fills it on insert (`#[model(default)]`).
    pub has_default: bool,
    /// The default's SQL expression, used when creating the table.
    pub default_sql: Option<&'static str>,
    /// A timestamp the ORM maintains.
    pub timestamp: Option<Timestamp>,
    /// A foreign key.
    pub references: Option<Reference>,
    /// The only values allowed, for a [`SqlEnum`](derive@crate::SqlEnum)
    /// column.
    pub values: Option<&'static [&'static str]>,
    /// The size of a vector column, from `#[model(dimensions = n)]`.
    pub dimensions: Option<u32>,
}

impl ColumnDef {
    #[doc(hidden)]
    pub const fn new(name: &'static str, kind: Kind, nullable: bool) -> Self {
        Self {
            name,
            kind,
            nullable,
            primary_key: false,
            auto_increment: false,
            unique: false,
            index: false,
            has_default: false,
            default_sql: None,
            timestamp: None,
            references: None,
            values: None,
            dimensions: None,
        }
    }

    #[doc(hidden)]
    pub const fn primary_key(mut self) -> Self {
        self.primary_key = true;
        self.auto_increment = self.kind.is_integer();
        self
    }

    #[doc(hidden)]
    pub const fn composite_key(mut self) -> Self {
        self.auto_increment = false;
        self
    }

    #[doc(hidden)]
    pub const fn unique(mut self) -> Self {
        self.unique = true;
        self
    }

    #[doc(hidden)]
    pub const fn index(mut self) -> Self {
        self.index = true;
        self
    }

    #[doc(hidden)]
    pub const fn default(mut self, sql: Option<&'static str>) -> Self {
        self.has_default = true;
        self.default_sql = sql;
        self
    }

    #[doc(hidden)]
    pub const fn timestamp(mut self, timestamp: Timestamp) -> Self {
        self.timestamp = Some(timestamp);
        self
    }

    #[doc(hidden)]
    pub const fn dimensions(mut self, dimensions: u32) -> Self {
        self.dimensions = Some(dimensions);
        self
    }

    #[doc(hidden)]
    pub const fn values(mut self, values: Option<&'static [&'static str]>) -> Self {
        self.values = values;
        self
    }

    #[doc(hidden)]
    pub const fn references(mut self, table: &'static str, column: &'static str, on_delete: Option<&'static str>) -> Self {
        self.references = Some(Reference { table, column, on_delete });
        self
    }
}

/// The current time for a timestamp column of this kind.
fn now(kind: Kind) -> Option<Value> {
    match kind {
        #[cfg(feature = "chrono")]
        Kind::DateTime => Some(Value::DateTime(chrono::Utc::now())),
        #[cfg(feature = "chrono")]
        Kind::NaiveDateTime => Some(Value::NaiveDateTime(chrono::Utc::now().naive_utc())),
        _ => None,
    }
}

/// `prefix` + `column`, allocating only when there is a prefix.
#[doc(hidden)]
pub fn column_name<'a>(prefix: &str, column: &'a str) -> Cow<'a, str> {
    if prefix.is_empty() {
        Cow::Borrowed(column)
    } else {
        Cow::Owned(format!("{}{}", prefix, column))
    }
}

/// The primary key column's definition.
pub(crate) fn primary_key<M: Model>() -> &'static ColumnDef {
    M::COLUMNS.iter().find(|c| c.primary_key).expect("models have a primary key")
}

fn value_of<M: Model>(model: &M, column: &'static str) -> Value {
    model.get(column).unwrap_or_else(|| panic!("{} has no column `{}`", std::any::type_name::<M>(), column))
}

/// The row whose `column` equals `key`, within the tenant scope.
pub(crate) async fn fetch_one_where<M: Model>(conn: &mut Conn<'_>, column: &'static str, key: Value) -> Result<Option<M>> {
    fetch_one_by(conn, vec![Cond::Compare(column, "=", key)]).await
}

/// `key column = value` for every primary key column of `model`.
fn key_conds<M: Model>(model: &M) -> Vec<Cond> {
    M::PRIMARY_KEYS.iter().map(|column| Cond::Compare(column, "=", value_of(model, column))).collect()
}

/// The first row matching `conds`, within the tenant scope.
async fn fetch_one_by<M: Model>(conn: &mut Conn<'_>, mut conds: Vec<Cond>) -> Result<Option<M>> {
    conds.extend(conn.scope().filter_for::<M>()?);
    let mut sql = Sql::new(conn.backend());
    sql.push("SELECT ").push(&column_list::<M>(conn.backend())).push(" FROM ").ident(M::TABLE);
    sql.where_clause(&conds);
    sql.push(" LIMIT 1");
    let (sql, args) = sql.finish();
    conn.fetch_optional(sql, args).await?.map(|row| M::from_row(&row)).transpose()
}

#[doc(hidden)]
pub async fn find<'c, M: Model>(ex: impl Executor<'c>, key: Value) -> Result<Option<M>> {
    fetch_one_where(&mut ex.into_conn(), M::PRIMARY_KEY, key).await
}

/// Fetches by a composite key: one value per primary key column, in order.
#[doc(hidden)]
pub async fn find_by_key<'c, M: Model>(ex: impl Executor<'c>, key: Vec<Value>) -> Result<Option<M>> {
    let conds = M::PRIMARY_KEYS.iter().zip(key).map(|(column, value)| Cond::Compare(column, "=", value)).collect();
    fetch_one_by(&mut ex.into_conn(), conds).await
}

/// The columns an `INSERT` writes and their values: all but
/// auto-increment keys and `default` columns, with timestamps set to now.
fn insert_values<M: Model>(model: &M) -> Vec<(&'static ColumnDef, Value)> {
    M::COLUMNS
        .iter()
        // The database fills auto-increment keys and `default` columns.
        .filter(|column| !column.auto_increment && !column.has_default)
        .map(|column| {
            let value = match column.timestamp {
                Some(_) => now(column.kind).unwrap_or_else(|| value_of(model, column.name)),
                None => value_of(model, column.name),
            };
            (column, value)
        })
        .collect()
}

/// `INSERT INTO table (columns) VALUES (values)`.
fn write_insert<M: Model>(sql: &mut Sql, backend: Backend, values: Vec<(&'static ColumnDef, Value)>) {
    sql.push("INSERT INTO ").ident(M::TABLE);
    if values.is_empty() && backend == Backend::MySql {
        sql.push(" () VALUES ()");
    } else if values.is_empty() {
        sql.push(" DEFAULT VALUES");
    } else {
        let columns: Vec<String> = values.iter().map(|(c, _)| crate::sql::ident(backend, c.name)).collect();
        sql.push(" (").push(&columns.join(", ")).push(") VALUES (");
        for (i, (_, value)) in values.into_iter().enumerate() {
            if i > 0 {
                sql.push(", ");
            }
            sql.arg(value);
        }
        sql.push(")");
    }
}

#[doc(hidden)]
pub async fn insert<'c, M: Model>(ex: impl Executor<'c>, model: &M) -> Result<M> {
    let mut conn = ex.into_conn();
    conn.scope().check_row(model)?;
    let backend = conn.backend();
    let mut sql = Sql::new(backend);
    write_insert::<M>(&mut sql, backend, insert_values(model));
    if backend == Backend::MySql {
        return insert_mysql(&mut conn, sql, model).await;
    }
    sql.push(" RETURNING ").push(&column_list::<M>(backend));
    let (sql, args) = sql.finish();
    let row = conn.fetch_optional(sql, args).await?.ok_or(Error::NotFound)?;
    M::from_row(&row)
}

/// MySQL has no `RETURNING`: insert, then read the row back by its key.
#[cfg(feature = "mysql")]
async fn insert_mysql<M: Model>(conn: &mut Conn<'_>, sql: Sql, model: &M) -> Result<M> {
    let (sql, args) = sql.finish();
    let id = conn.insert_mysql(sql, args).await?;
    fetch_one_by(conn, mysql_key(model, id)).await?.ok_or(Error::NotFound)
}

#[cfg(not(feature = "mysql"))]
async fn insert_mysql<M: Model>(_: &mut Conn<'_>, _: Sql, _: &M) -> Result<M> {
    unreachable!("MySQL connections need the `mysql` feature")
}

/// The key of a row MySQL just wrote, as conditions: `id` from
/// `LAST_INSERT_ID()` for an auto-increment key, else the model's own key.
#[cfg(feature = "mysql")]
fn mysql_key<M: Model>(model: &M, id: u64) -> Vec<Cond> {
    let pk = primary_key::<M>();
    match (pk.auto_increment, pk.kind) {
        (true, Kind::I32) => vec![Cond::Compare(pk.name, "=", Value::I32(id as i32))],
        (true, _) => vec![Cond::Compare(pk.name, "=", Value::I64(id as i64))],
        (false, _) => key_conds(model),
    }
}

/// What [`upsert`](crate::Model) and `insert_or_ignore` do when a row with
/// the same unique columns already exists: `OnConflict::on(Product::SKU)`.
///
/// The columns must have a unique constraint or index together
/// (`#[model(unique)]` for one column). MySQL ignores them and reacts to a
/// conflict on any unique key.
pub struct OnConflict<M> {
    target: Vec<&'static str>,
    update: Option<Vec<&'static str>>,
    _marker: PhantomData<fn() -> M>,
}

impl<M> Clone for OnConflict<M> {
    fn clone(&self) -> Self {
        Self { target: self.target.clone(), update: self.update.clone(), _marker: PhantomData }
    }
}

impl<M> std::fmt::Debug for OnConflict<M> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("OnConflict").field("target", &self.target).field("update", &self.update).finish()
    }
}

impl<M: Model> OnConflict<M> {
    /// A conflict on `column`.
    pub fn on<T>(column: Column<M, T>) -> Self {
        Self { target: vec![column.name()], update: None, _marker: PhantomData }
    }

    /// A conflict on several columns together: add another one.
    pub fn and<T>(mut self, column: Column<M, T>) -> Self {
        self.target.push(column.name());
        self
    }

    /// On conflict, [`upsert`](crate::Model) overwrites only the columns
    /// named this way (call again for more), instead of every column but
    /// the primary key, the conflict columns and `created_at`.
    pub fn update<T>(mut self, column: Column<M, T>) -> Self {
        self.update.get_or_insert_with(Vec::new).push(column.name());
        self
    }

    /// The columns an upsert overwrites, from those the insert writes.
    fn update_columns(&self, inserted: &[(&'static ColumnDef, Value)]) -> Vec<&'static str> {
        match &self.update {
            Some(columns) => columns.clone(),
            None => inserted
                .iter()
                .map(|(c, _)| *c)
                .filter(|c| !c.primary_key && c.timestamp != Some(Timestamp::CreatedAt) && !self.target.contains(&c.name))
                .map(|c| c.name)
                .collect(),
        }
    }
}

/// `ON CONFLICT (target)`, or nothing on MySQL.
fn write_conflict_target<M>(sql: &mut Sql, backend: Backend, conflict: &OnConflict<M>) {
    if backend != Backend::MySql {
        let target: Vec<String> = conflict.target.iter().map(|c| crate::sql::ident(backend, c)).collect();
        sql.push(" ON CONFLICT (").push(&target.join(", ")).push(")");
    }
}

#[doc(hidden)]
pub async fn upsert<'c, M: Model>(ex: impl Executor<'c>, model: &M, conflict: &OnConflict<M>) -> Result<M> {
    let mut conn = ex.into_conn();
    conn.scope().check_row(model)?;
    let guard = conn.scope().filter_for::<M>()?;
    let result = upsert_scoped(&mut conn, model, conflict, guard.is_some()).await;
    match result {
        // The conflicting row belongs to another tenant, so it was left alone.
        Err(Error::NotFound) if guard.is_some() => Err(other_tenants_row::<M>()),
        result => result,
    }
}

fn other_tenants_row<M: Model>() -> Error {
    Error::WrongTenant(format!("a `{}` row with the same key belongs to another tenant", M::TABLE))
}

/// `col = excluded.col` on conflict (and `version = version + 1`); with a
/// tenant column, only when the existing row has the same tenant (else the
/// row is left as it is).
fn write_conflict_update<M: Model>(sql: &mut Sql, backend: Backend, update: &[&'static str], guarded: bool) {
    let tenant = M::TENANT.filter(|_| guarded);
    let mut update: Vec<&'static str> = update.iter().copied().filter(|c| Some(*c) != M::VERSION).collect();
    update.extend(M::VERSION);
    let excluded = crate::sql::ident(backend, "excluded");
    // The value a column gets: the new row's, or the bumped version.
    let new_value = |sql: &mut Sql, column: &str| {
        if Some(column) == M::VERSION {
            sql.ident(M::TABLE).push(".").ident(column).push(" + 1");
        } else {
            sql.push(&excluded).push(".").ident(column);
        }
    };
    if backend == Backend::MySql {
        sql.push(" AS ").push(&excluded).push(" ON DUPLICATE KEY UPDATE ");
        for (i, column) in update.iter().enumerate() {
            if i > 0 {
                sql.push(", ");
            }
            sql.ident(column).push(" = ");
            match tenant {
                // Assignments run left to right and the tenant column never
                // changes here, so it compares the existing row's tenant.
                Some(tenant) => {
                    sql.push("IF(").ident(M::TABLE).push(".").ident(tenant).push(" <=> ").push(&excluded).push(".").ident(tenant);
                    sql.push(", ");
                    new_value(sql, column);
                    sql.push(", ").ident(M::TABLE).push(".").ident(column).push(")");
                }
                None => new_value(sql, column),
            }
        }
        return;
    }
    sql.push(" DO UPDATE SET ");
    for (i, column) in update.iter().enumerate() {
        if i > 0 {
            sql.push(", ");
        }
        sql.ident(column).push(" = ");
        new_value(sql, column);
    }
    if let Some(tenant) = tenant {
        sql.push(" WHERE ").ident(M::TABLE).push(".").ident(tenant).push(" = ").ident("excluded").push(".").ident(tenant);
    }
}

async fn upsert_scoped<M: Model>(conn: &mut Conn<'_>, model: &M, conflict: &OnConflict<M>, guarded: bool) -> Result<M> {
    let backend = conn.backend();
    let inserted = insert_values(model);
    let mut update = conflict.update_columns(&inserted);
    if update.is_empty() {
        // Every column is a key: a no-op update, so the row still comes back.
        update.push(conflict.target[0]);
    }
    let mut sql = Sql::new(backend);
    write_insert::<M>(&mut sql, backend, inserted);
    let pk = primary_key::<M>();
    if backend == Backend::MySql {
        write_conflict_update::<M>(&mut sql, backend, &update, guarded);
        // `LAST_INSERT_ID(id)` makes an update report the existing row's id.
        if pk.auto_increment {
            sql.push(", ").ident(pk.name).push(" = LAST_INSERT_ID(").ident(pk.name).push(")");
        }
        return upsert_mysql(conn, sql, model, conflict).await;
    }
    write_conflict_target(&mut sql, backend, conflict);
    write_conflict_update::<M>(&mut sql, backend, &update, guarded);
    sql.push(" RETURNING ").push(&column_list::<M>(backend));
    let (sql, args) = sql.finish();
    let row = conn.fetch_optional(sql, args).await?.ok_or(Error::NotFound)?;
    M::from_row(&row)
}

/// Reads the upserted row back: by `LAST_INSERT_ID()` for an
/// auto-increment key, else by the conflict columns, which the update
/// leaves alone.
#[cfg(feature = "mysql")]
async fn upsert_mysql<M: Model>(conn: &mut Conn<'_>, sql: Sql, model: &M, conflict: &OnConflict<M>) -> Result<M> {
    let (sql, args) = sql.finish();
    let id = conn.insert_mysql(sql, args).await?;
    let pk = primary_key::<M>();
    if pk.auto_increment {
        return fetch_one_by(conn, mysql_key(model, id)).await?.ok_or(Error::NotFound);
    }
    let conds = conflict.target.iter().map(|c| crate::sql::Cond::Compare(c, "=", value_of(model, c))).collect();
    crate::Query::<M>::new().cond(crate::sql::Cond::And(conds)).fetch(conn).await?.into_iter().next().ok_or(Error::NotFound)
}

#[cfg(not(feature = "mysql"))]
async fn upsert_mysql<M: Model>(_: &mut Conn<'_>, _: Sql, _: &M, _: &OnConflict<M>) -> Result<M> {
    unreachable!("MySQL connections need the `mysql` feature")
}

#[doc(hidden)]
pub async fn insert_or_ignore<'c, M: Model>(ex: impl Executor<'c>, model: &M, conflict: &OnConflict<M>) -> Result<Option<M>> {
    let mut conn = ex.into_conn();
    conn.scope().check_row(model)?;
    let backend = conn.backend();
    let mut sql = Sql::new(backend);
    write_insert::<M>(&mut sql, backend, insert_values(model));
    if backend == Backend::MySql {
        return insert_or_ignore_mysql(&mut conn, sql, model).await;
    }
    write_conflict_target(&mut sql, backend, conflict);
    sql.push(" DO NOTHING RETURNING ").push(&column_list::<M>(backend));
    let (sql, args) = sql.finish();
    conn.fetch_optional(sql, args).await?.map(|row| M::from_row(&row)).transpose()
}

/// A plain insert, where a unique violation means the row exists. Not
/// `INSERT IGNORE`, which also turns other errors into warnings, nor a
/// no-op `ON DUPLICATE KEY UPDATE`: sqlx reports found rows, so that
/// counts 1 whether or not it inserted.
#[cfg(feature = "mysql")]
async fn insert_or_ignore_mysql<M: Model>(conn: &mut Conn<'_>, sql: Sql, model: &M) -> Result<Option<M>> {
    let (sql, args) = sql.finish();
    match conn.insert_mysql_unless_duplicate(sql, args).await? {
        None => Ok(None),
        Some(id) => fetch_one_by(conn, mysql_key(model, id)).await,
    }
}

#[cfg(not(feature = "mysql"))]
async fn insert_or_ignore_mysql<M: Model>(_: &mut Conn<'_>, _: Sql, _: &M) -> Result<Option<M>> {
    unreachable!("MySQL connections need the `mysql` feature")
}

#[doc(hidden)]
pub async fn update<'c, M: Model>(ex: impl Executor<'c>, model: &M) -> Result<M> {
    let mut conn = ex.into_conn();
    conn.scope().check_row(model)?;
    let tenant = conn.scope().filter_for::<M>()?;
    let backend = conn.backend();
    let mut sql = Sql::new(backend);
    sql.push("UPDATE ").ident(M::TABLE).push(" SET ");
    let mut first = true;
    for column in M::COLUMNS.iter().filter(|c| !c.primary_key) {
        if !first {
            sql.push(", ");
        }
        first = false;
        if Some(column.name) == M::VERSION {
            sql.ident(column.name).push(" = ").ident(column.name).push(" + 1");
            continue;
        }
        let value = match column.timestamp {
            Some(Timestamp::UpdatedAt) => now(column.kind).unwrap_or_else(|| value_of(model, column.name)),
            _ => value_of(model, column.name),
        };
        sql.ident(column.name).push(" = ").arg(value);
    }
    if first {
        // Only a primary key: nothing to change, but still check the row exists.
        return fetch_one_by(&mut conn, key_conds(model)).await?.ok_or(Error::NotFound);
    }
    let key = key_conds(model);
    // The stored row must be the tenant's too, not only the new values.
    let mut conds = key.clone();
    conds.extend(tenant);
    conds.extend(version_cond(model));
    sql.where_clause(&conds);
    if backend == Backend::MySql {
        // No `RETURNING`, and affected rows count only changed rows; with
        // a version column every match changes it, so 0 means no match.
        let (sql, args) = sql.finish();
        let changed = conn.execute(sql, args).await?;
        if changed == 0 && M::VERSION.is_some() {
            return Err(missing_or_stale::<M>(&mut conn, key).await);
        }
        return fetch_one_by(&mut conn, key).await?.ok_or(Error::NotFound);
    }
    sql.push(" RETURNING ").push(&column_list::<M>(backend));
    let (sql, args) = sql.finish();
    match conn.fetch_optional(sql, args).await? {
        Some(row) => M::from_row(&row),
        None => Err(missing_or_stale::<M>(&mut conn, key).await),
    }
}

/// `version = <loaded value>`, for models with a version column.
fn version_cond<M: Model>(model: &M) -> Option<Cond> {
    M::VERSION.map(|column| Cond::Compare(column, "=", value_of(model, column)))
}

/// Why a keyed write matched no row: the row is gone ([`Error::NotFound`])
/// or, with a version column, another write changed it first
/// ([`Error::StaleRecord`]).
async fn missing_or_stale<M: Model>(conn: &mut Conn<'_>, key: Vec<Cond>) -> Error {
    if M::VERSION.is_none() {
        return Error::NotFound;
    }
    match fetch_one_by::<M>(conn, key).await {
        Ok(Some(_)) => Error::StaleRecord(format!("this `{}` row was changed since it was loaded", M::TABLE)),
        Ok(None) => Error::NotFound,
        Err(error) => error,
    }
}

#[doc(hidden)]
pub async fn delete<'c, M: Model>(ex: impl Executor<'c>, model: &M) -> Result<()> {
    let mut conn = ex.into_conn();
    let key = key_conds(model);
    let mut conds = key.clone();
    conds.extend(conn.scope().filter_for::<M>()?);
    conds.extend(version_cond(model));
    let mut sql = Sql::new(conn.backend());
    sql.push("DELETE FROM ").ident(M::TABLE);
    sql.where_clause(&conds);
    let (sql, args) = sql.finish();
    match conn.execute(sql, args).await? {
        0 => Err(missing_or_stale::<M>(&mut conn, key).await),
        _ => Ok(()),
    }
}

/// Rows per bulk `INSERT`: under the database's limit on bound parameters
/// (32766 in SQLite, 65535 elsewhere), and at most 1000.
fn rows_per_statement(backend: Backend, columns: usize) -> usize {
    let limit = match backend {
        Backend::Sqlite => 32_766,
        _ => 65_535,
    };
    (limit / columns.max(1)).clamp(1, 1000)
}

#[doc(hidden)]
pub async fn insert_many<'c, M: Model>(ex: impl Executor<'c>, models: &[M]) -> Result<Vec<M>> {
    bulk(ex, models, None).await
}

#[doc(hidden)]
pub async fn upsert_many<'c, M: Model>(ex: impl Executor<'c>, models: &[M], conflict: &OnConflict<M>) -> Result<Vec<M>> {
    if conflict.target.is_empty() {
        return Err(Error::Config("upsert_many needs at least one conflict column".into()));
    }
    // Checked first, so a bad batch writes nothing on any database.
    let mut seen = std::collections::HashSet::new();
    if !models.iter().all(|model| seen.insert(key_of(model, &conflict.target))) {
        return Err(Error::Config("two rows in one upsert_many have the same conflict key".into()));
    }
    bulk(ex, models, Some(conflict)).await
}

/// Inserts (or upserts) in chunks; several chunks on a bare pool run in one
/// transaction, so a failure inserts nothing.
async fn bulk<'c, M: Model>(ex: impl Executor<'c>, models: &[M], conflict: Option<&OnConflict<M>>) -> Result<Vec<M>> {
    let Some(first) = models.first() else { return Ok(Vec::new()) };
    let mut conn = ex.into_conn();
    for model in models {
        conn.scope().check_row(model)?;
    }
    let backend = conn.backend();
    let columns = insert_values(first).len();
    if columns == 0 {
        // Only database-filled columns: rows can't share a statement.
        let mut stored = Vec::with_capacity(models.len());
        for model in models {
            stored.push(match conflict {
                None => insert(&mut conn, model).await?,
                Some(conflict) => upsert(&mut conn, model, conflict).await?,
            });
        }
        return Ok(stored);
    }
    let per_statement = rows_per_statement(backend, columns);
    match &mut conn {
        Conn::Db(db) if models.len() > per_statement => {
            let mut tx = db.begin().await?;
            let stored = bulk_chunks(&mut Conn::Tx(&mut tx), models, conflict, per_statement).await?;
            tx.commit().await?;
            Ok(stored)
        }
        _ => bulk_chunks(&mut conn, models, conflict, per_statement).await,
    }
}

async fn bulk_chunks<M: Model>(conn: &mut Conn<'_>, models: &[M], conflict: Option<&OnConflict<M>>, per_statement: usize) -> Result<Vec<M>> {
    let backend = conn.backend();
    let guarded = conn.scope().filter_for::<M>()?.is_some();
    let pk = primary_key::<M>();
    let mut stored = Vec::with_capacity(models.len());
    for chunk in models.chunks(per_statement) {
        let rows: Vec<Vec<(&'static ColumnDef, Value)>> = chunk.iter().map(insert_values).collect();
        let mut sql = Sql::new(backend);
        sql.push("INSERT INTO ").ident(M::TABLE).push(" (");
        for (i, (column, _)) in rows[0].iter().enumerate() {
            if i > 0 {
                sql.push(", ");
            }
            sql.ident(column.name);
        }
        sql.push(") VALUES ");
        let update = conflict.map(|conflict| {
            let mut update = conflict.update_columns(&rows[0]);
            if update.is_empty() {
                update.push(conflict.target[0]);
            }
            update
        });
        for (i, row) in rows.into_iter().enumerate() {
            sql.push(if i == 0 { "(" } else { ", (" });
            for (j, (_, value)) in row.into_iter().enumerate() {
                if j > 0 {
                    sql.push(", ");
                }
                sql.arg(value);
            }
            sql.push(")");
        }
        if let (Some(conflict), Some(update)) = (conflict, &update) {
            if backend != Backend::MySql {
                write_conflict_target(&mut sql, backend, conflict);
            }
            write_conflict_update::<M>(&mut sql, backend, update, guarded);
        }

        let fetched: Vec<M> = if backend == Backend::MySql {
            bulk_mysql(conn, sql, chunk, conflict, pk).await?
        } else {
            sql.push(" RETURNING ").push(&column_list::<M>(backend));
            let (text, args) = sql.finish();
            conn.fetch_all(text, args).await?.iter().map(M::from_row).collect::<Result<_>>()?
        };
        if guarded && conflict.is_some() && fetched.len() < chunk.len() {
            // Rows of another tenant with the same keys were left alone.
            return Err(other_tenants_row::<M>());
        }
        stored.extend(in_input_order(chunk, fetched, conflict, pk)?);
    }
    Ok(stored)
}

/// MySQL has no `RETURNING`: insert, then read the rows back.
#[cfg(feature = "mysql")]
async fn bulk_mysql<M: Model>(conn: &mut Conn<'_>, sql: Sql, chunk: &[M], conflict: Option<&OnConflict<M>>, pk: &ColumnDef) -> Result<Vec<M>> {
    let (text, args) = sql.finish();
    let first_id = conn.insert_mysql(text, args).await?;
    match conflict {
        // A multi-row INSERT gets consecutive auto-increment IDs.
        None if pk.auto_increment => {
            let first = match pk.kind {
                Kind::I32 => Value::I32(first_id as i32),
                _ => Value::I64(first_id as i64),
            };
            let rows = crate::Query::<M>::new()
                .cond(crate::sql::Cond::Compare(pk.name, ">=", first))
                .order_by_column(pk.name)
                .limit(chunk.len() as u64)
                .fetch(conn)
                .await?;
            if rows.len() != chunk.len() {
                return Err(Error::Config("MySQL didn't assign consecutive IDs to a bulk insert".into()));
            }
            Ok(rows)
        }
        None => fetch_by_keys(conn, chunk, M::PRIMARY_KEYS).await,
        Some(conflict) => fetch_by_keys(conn, chunk, &conflict.target).await,
    }
}

#[cfg(not(feature = "mysql"))]
async fn bulk_mysql<M: Model>(_: &mut Conn<'_>, _: Sql, _: &[M], _: Option<&OnConflict<M>>, _: &ColumnDef) -> Result<Vec<M>> {
    unreachable!("MySQL connections need the `mysql` feature")
}

/// Rows whose `keys` columns match one of `models`.
#[cfg(feature = "mysql")]
async fn fetch_by_keys<M: Model>(conn: &mut Conn<'_>, models: &[M], keys: &[&'static str]) -> Result<Vec<M>> {
    use crate::sql::Cond;
    let any = models
        .iter()
        .map(|model| Cond::And(keys.iter().map(|key| Cond::Compare(key, "=", value_of(model, key))).collect()))
        .collect();
    crate::Query::<M>::new().cond(Cond::Or(any)).fetch(conn).await
}

/// Puts stored rows in the order of the input: by the generated key for a
/// plain insert (IDs follow insertion order), else by key values. SQLite
/// doesn't promise `RETURNING` order.
fn in_input_order<M: Model>(input: &[M], mut stored: Vec<M>, conflict: Option<&OnConflict<M>>, pk: &ColumnDef) -> Result<Vec<M>> {
    if conflict.is_none() && pk.auto_increment {
        stored.sort_by_key(|row| match value_of(row, pk.name) {
            Value::I32(id) => i64::from(id),
            Value::I64(id) => id,
            _ => 0,
        });
        return Ok(stored);
    }
    let keys: Vec<&'static str> = match conflict {
        Some(conflict) => conflict.target.clone(),
        None => M::PRIMARY_KEYS.to_vec(),
    };
    let mut by_key: std::collections::HashMap<Vec<Value>, M> = stored.into_iter().map(|row| (key_of(&row, &keys), row)).collect();
    input
        .iter()
        .map(|model| by_key.remove(&key_of(model, &keys)).ok_or(Error::NotFound))
        .collect::<Result<Vec<M>>>()
        .map_err(|_| Error::Config("two rows in one bulk upsert have the same key".into()))
}

fn key_of<M: Model>(model: &M, keys: &[&'static str]) -> Vec<Value> {
    keys.iter().map(|key| value_of(model, key).key()).collect()
}

/// Compile-time check used by the derive for relation foreign keys.
#[doc(hidden)]
pub const fn has_column(columns: &[ColumnDef], name: &str) -> bool {
    let mut i = 0;
    while i < columns.len() {
        let (a, b) = (columns[i].name.as_bytes(), name.as_bytes());
        if a.len() == b.len() {
            let mut j = 0;
            while j < a.len() && a[j] == b[j] {
                j += 1;
            }
            if j == a.len() {
                return true;
            }
        }
        i += 1;
    }
    false
}
